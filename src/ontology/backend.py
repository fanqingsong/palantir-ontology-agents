"""Ontology persistence backend protocol."""

from __future__ import annotations

from typing import Any, Optional, Protocol

from src.ontology.schema import Entity, EntityType, Relationship, RelationshipType


class OntologyBackend(Protocol):
    """Storage and graph operations used by OntologyStore."""

    def add_entity(self, entity: Entity) -> str: ...
    def get_entity(self, entity_id: str) -> Optional[Entity]: ...
    def get_entity_by_name(self, name: str) -> Optional[Entity]: ...
    def remove_entity(self, entity_id: str) -> bool: ...

    def add_relationship(self, relationship: Relationship) -> str: ...
    def get_relationship(self, rel_id: str) -> Optional[Relationship]: ...

    def query_by_type(self, entity_type: EntityType) -> list[Entity]: ...
    def query_by_attribute(self, key: str, value: Any) -> list[Entity]: ...
    def search(self, query: str) -> list[Entity]: ...

    def get_neighbors(
        self,
        entity_id: str,
        relationship_type: Optional[RelationshipType] = None,
        direction: str = "both",
    ) -> list[tuple[Entity, Relationship]]: ...

    def traverse(
        self,
        entity_id: str,
        hops: int = 2,
        relationship_type: Optional[RelationshipType] = None,
    ) -> dict[str, Any]: ...

    def find_path(
        self, source_id: str, target_id: str, max_hops: int = 5
    ) -> Optional[list[str]]: ...

    def get_dependency_chains(
        self,
        entity_id: str,
        rel_types: Optional[list[RelationshipType]] = None,
        max_depth: int = 5,
    ) -> list[list[str]]: ...

    def calculate_exposure_score(
        self, entity_id: str, threat_ids: Optional[list[str]] = None
    ) -> float: ...

    def to_dict(self) -> dict[str, Any]: ...
    def load_dict(self, data: dict[str, Any]) -> None: ...

    @property
    def entity_count(self) -> int: ...

    @property
    def relationship_count(self) -> int: ...

    def all_entities(self) -> list[Entity]: ...
    def all_relationships(self) -> list[Relationship]: ...
